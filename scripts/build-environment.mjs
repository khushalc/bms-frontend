#!/usr/bin/env node
/**
 * Generates one of `src/environments/environment[.<mode>].ts` from the single
 * `.env` file. The `.env` values are the same — only the output file and the
 * `production` flag differ per mode.
 *
 * Usage:
 *   node scripts/build-environment.mjs --dev    # -> src/environments/environment.ts       (production=false)
 *   node scripts/build-environment.mjs --test   # -> src/environments/environment.test.ts  (production=false)
 *   node scripts/build-environment.mjs --prod   # -> src/environments/environment.prod.ts  (production=true)
 *
 * The Angular build swaps `environment.ts` for the mode-specific file via
 * `fileReplacements` in angular.json (production, test).
 *
 * All values are baked into the client bundle at build time. NEVER put
 * secrets here — anything in these files ships to the browser.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const ENV_FILE = resolve(ROOT, '.env');
const EXAMPLE_FILE = resolve(ROOT, '.env.example');

const WHITELIST = /** @type {const} */ ([
  { key: 'API_BASE_URL', out: 'apiBaseUrl', required: true },
  { key: 'APP_NAME', out: 'appName', required: false, default: 'bms-frontend' },
]);

const MODES = {
  dev: { file: 'src/environments/environment.ts', production: false },
  test: { file: 'src/environments/environment.test.ts', production: false },
  prod: { file: 'src/environments/environment.prod.ts', production: true },
};

function parseArgs(argv) {
  const flags = new Set();
  for (const raw of argv.slice(2)) {
    if (raw.startsWith('--')) flags.add(raw.slice(2));
  }
  return flags;
}

function pickMode(flags) {
  const modes = Object.keys(MODES).filter((m) => flags.has(m));
  if (modes.length === 0) {
    throw new Error('Missing mode flag. Pass one of: --dev | --test | --prod');
  }
  if (modes.length > 1) {
    throw new Error(`Pass exactly one mode flag; got: ${modes.map((m) => `--${m}`).join(' ')}`);
  }
  return modes[0];
}

function parseDotEnv(text) {
  const result = {};
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq < 0) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    result[key] = value;
  }
  return result;
}

function buildEnvironmentObject(dotenv) {
  const out = {};
  for (const spec of WHITELIST) {
    const raw = dotenv[spec.key];
    if (raw === undefined || raw === '') {
      if (spec.required && spec.default === undefined) {
        throw new Error(`Missing required env key: ${spec.key} (add it to .env)`);
      }
      out[spec.out] = spec.default;
    } else {
      out[spec.out] = raw;
    }
  }
  return out;
}

function render(env, production, mode) {
  const body = Object.entries(env)
    .map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`)
    .join('\n');
  return `// AUTO-GENERATED by scripts/build-environment.mjs (--${mode}) — do not edit by hand.
export const environment = {
  production: ${production},
${body}
};
`;
}

function main() {
  const flags = parseArgs(process.argv);
  const mode = pickMode(flags);
  const { file, production } = MODES[mode];
  const outFile = resolve(ROOT, file);

  let dotenv = {};
  if (existsSync(ENV_FILE)) {
    dotenv = parseDotEnv(readFileSync(ENV_FILE, 'utf8'));
    console.log(`✓ read .env`);
  } else if (existsSync(EXAMPLE_FILE)) {
    dotenv = parseDotEnv(readFileSync(EXAMPLE_FILE, 'utf8'));
    console.warn(`! .env not found — falling back to .env.example`);
  } else {
    throw new Error('Neither .env nor .env.example found');
  }

  const env = buildEnvironmentObject(dotenv);
  writeFileSync(outFile, render(env, production, mode), 'utf8');
  console.log(`✓ wrote ${file} (--${mode}, production=${production})`);
}

try {
  main();
} catch (err) {
  console.error(`✗ ${err.message}`);
  process.exit(1);
}
